import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const names = ["mobile-automation", "build-mcp-exe"];
const skills = Object.fromEntries(names.map(name => [
	name, fs.readFileSync(path.join(root, "skills", name, "SKILL.md"), "utf8")
]));
const generated = "// Generated by scripts/embed-skills.mjs; edit canonical skills markdown instead.\n" +
	"export const SKILLS: Record<string, string> = " + JSON.stringify(skills, null, "\t") + ";\n";
const target = path.join(root, "src", "embedded-skills.ts");
if (!fs.existsSync(target) || fs.readFileSync(target, "utf8") !== generated) {
	fs.writeFileSync(target, generated, "utf8");
}
